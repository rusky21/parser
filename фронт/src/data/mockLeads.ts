export const generateLeadsFor = (niche: string, city: string, count: number): Lead[] => {
  const statuses: Lead['status'][] = ['No Website', 'No SSL', 'Not Responsive', 'No Analytics', 'HTTPS OK'];
  const leads: Lead[] = [];

  for (let i = 1; i <= count; i++) {
    const status = statuses[i % statuses.length];
    leads.push({
      id: i,
      name: `${niche} #${i}`,
      rating: 3 + (i % 3),
      category: niche,
      phone: `+7 843 ${100 + i * 7}-${1000 + i * 13}`,
      telegram: `@${niche.toLowerCase().replace(/[^a-z0-9]/g, '')}_${city.toLowerCase().slice(0, 3)}_${i}`,
      status: status,
      website: status === 'No Website' ? undefined : `http://${niche.toLowerCase().slice(0, 5)}${i}.ru`,
      hasWebsite: status !== 'No Website',
      mobileFriendly: status !== 'Not Responsive',
      hasSsl: status !== 'No SSL' && status !== 'No Website',
      hasAnalytics: status !== 'No Analytics' && status !== 'No Website',
      address: `ул. Центральная, ${i * 4}, ${city}`,
    });
  }

  return leads;
};
